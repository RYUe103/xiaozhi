const PageViewTracker = () => {
  const { isAuthenticated } = useAuthContext();
  const location = useLocation();
  useEffect(() => {
    if (!isAuthenticated) return;
    const key = `sansuo-page-view:${location.pathname}`;
    const now = Date.now();
    if (now - Number(sessionStorage.getItem(key) || 0) < 30_000) return;
    sessionStorage.setItem(key, String(now));
    let sessionId = sessionStorage.getItem('sansuo-page-session');
    if (!sessionId) {
      sessionId = globalThis.crypto?.randomUUID?.() || `session-${now}`;
      sessionStorage.setItem('sansuo-page-session', sessionId);
    }
    void request
      .post(`${apiBaseUrl()}/api/sansuo-usage/events`, {
        eventType: 'page_view',
        pagePath: location.pathname,
        sessionId,
      })
      .catch(() => undefined);
  }, [isAuthenticated, location.pathname]);
  return null;
};

